pub fn lookup(word: &str) -> Option<&'static str> {
    let needle = format!("\n{} ", word.to_lowercase());
    let start = DICT_EN.find(&needle)? + 1;
    let rest = &DICT_EN[start..];
    let end = rest.find('\n')?;
    let line = &rest[..end];
    let (_, phones) = line.split_once(' ')?;
    Some(phones)
}

